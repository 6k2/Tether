//! Built-in theme definitions and the palette derivation shared with user themes.
//!
//! Themes are written as a compact `Spec` (the scheme's published colours) and the
//! in-between tones (raised surfaces, borders, dim/faint text, translucent accents)
//! are derived so every theme gets the same visual rhythm and readable contrast.

use eframe::egui::Color32;

use crate::theme::Palette;
use crate::themes::{Gradient, Source, Theme, contrast, lerp_color};

/// Minimum WCAG contrast the derived dim text keeps against every surface.
const DIM_TARGET: f32 = 3.3;
const FAINT_TARGET: f32 = 2.1;

/// The handful of colours a theme defines; everything else is derived.
#[derive(Debug, Clone, Copy)]
pub(crate) struct Colors {
    pub dark: bool,
    /// Window chrome behind panels.
    pub bg: Color32,
    /// Cards, tab bodies.
    pub surface: Color32,
    pub text: Color32,
    pub accent: Color32,
    pub blue: Color32,
    pub danger: Color32,
    pub warn: Color32,
    pub success: Color32,
    pub term_bg: Color32,
    pub term_fg: Color32,
    pub cursor: Color32,
    /// Solid selection colour; `None` derives a translucent accent.
    pub selection: Option<Color32>,
    pub ansi: [Color32; 16],
}

pub(crate) const fn hex(v: u32) -> Color32 {
    Color32::from_rgb((v >> 16) as u8, (v >> 8) as u8, v as u8)
}

fn mix(a: Color32, b: Color32, t: f32) -> Color32 {
    lerp_color(a, b, t)
}

fn with_alpha(c: Color32, alpha: u8) -> Color32 {
    Color32::from_rgba_unmultiplied(c.r(), c.g(), c.b(), alpha)
}

/// Strongest blend of `fg` toward `base` that still keeps `target` contrast on all `backs`.
fn readable_blend(fg: Color32, base: Color32, start: f32, target: f32, backs: &[Color32]) -> Color32 {
    let mut t = start;
    loop {
        let c = mix(fg, base, t);
        if t <= 0.0 || backs.iter().all(|b| contrast(c, *b) >= target) {
            return c;
        }
        t = (t - 0.02).max(0.0);
    }
}

/// Pushes `fg` toward white (dark themes) or black until it reaches `target` contrast on `back`.
pub(crate) fn ensure_contrast(fg: Color32, back: Color32, target: f32, dark: bool) -> Color32 {
    let pole = if dark { Color32::WHITE } else { Color32::BLACK };
    let mut t = 0.0;
    loop {
        let c = mix(fg, pole, t);
        if t >= 1.0 || contrast(c, back) >= target {
            return c;
        }
        t = (t + 0.04).min(1.0);
    }
}

/// Builds a full palette from the defining colours.
pub(crate) fn derive_palette(c: &Colors) -> Palette {
    let (bg, surface, text, accent) = (c.bg, c.surface, c.text, c.accent);
    let lift = |t: f32| mix(surface, text, t);
    let (surface_2, surface_3) = if c.dark { (lift(0.045), lift(0.095)) } else { (lift(0.035), lift(0.075)) };
    let border = lift(if c.dark { 0.14 } else { 0.13 });
    let backs = [bg, surface, surface_2];
    let text_dim = readable_blend(text, surface, 0.42, DIM_TARGET, &backs);
    let text_faint = readable_blend(text, surface, 0.62, FAINT_TARGET, &backs);
    let ink = if c.dark { mix(c.term_bg, Color32::BLACK, 0.5) } else { mix(text, Color32::BLACK, 0.4) };
    let on_accent = if contrast(ink, accent) >= contrast(Color32::WHITE, accent) { ink } else { Color32::WHITE };
    Palette {
        dark: c.dark,
        bg,
        surface,
        surface_2,
        surface_3,
        border,
        text,
        text_dim,
        text_faint,
        accent,
        accent_soft: with_alpha(accent, if c.dark { 0x5c } else { 0x3a }),
        blue: c.blue,
        danger: c.danger,
        warn: c.warn,
        success: c.success,
        shadow: Color32::from_black_alpha(if c.dark { 140 } else { 36 }),
        on_accent,
        icon_page: lift(if c.dark { 0.2 } else { 0.16 }),
        icon_page_edge: lift(if c.dark { 0.32 } else { 0.28 }),
        row_separator: if c.dark { Color32::from_black_alpha(0x50) } else { with_alpha(text, 0x12) },
        term_bg: c.term_bg,
        term_fg: c.term_fg,
        term_cursor: c.cursor,
        term_selection: c.selection.unwrap_or(with_alpha(accent, if c.dark { 0x70 } else { 0x48 })),
        ansi: c.ansi,
    }
}

struct Spec {
    name: &'static str,
    tagline: &'static str,
    dark: bool,
    bg: u32,
    surface: u32,
    text: u32,
    accent: u32,
    blue: u32,
    danger: u32,
    warn: u32,
    success: u32,
    term_bg: u32,
    term_fg: u32,
    cursor: u32,
    selection: Option<u32>,
    ansi: [u32; 16],
}

impl Spec {
    fn build(&self) -> Theme {
        let colors = Colors {
            dark: self.dark,
            bg: hex(self.bg),
            surface: hex(self.surface),
            text: hex(self.text),
            accent: hex(self.accent),
            blue: hex(self.blue),
            danger: hex(self.danger),
            warn: hex(self.warn),
            success: hex(self.success),
            term_bg: hex(self.term_bg),
            term_fg: hex(self.term_fg),
            cursor: hex(self.cursor),
            selection: self.selection.map(hex),
            ansi: self.ansi.map(hex),
        };
        let gradient = GRADIENTS.iter().find(|(n, ..)| *n == self.name).map(|&(_, start, end)| Gradient { start: hex(start), end: hex(end), vertical: true });
        let mut theme = Theme::new(self.name, self.tagline, derive_palette(&colors), Source::Builtin);
        theme.gradient = gradient;
        theme
    }
}

